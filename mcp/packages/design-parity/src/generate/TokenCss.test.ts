import assert from "node:assert/strict";
import { describe, it } from "node:test";
import type { TokensModel } from "../DesignModel.js";
import { colourTokenVariable, renderTokensCss, tokenVariableName } from "./TokenCss.js";

const TOKENS: TokensModel = {
    sets: [],
    themes: [],
    activeThemes: [],
    activeSets: [],
    tokens: [
        { setName: "core", name: "color.primary.500", type: "color", value: "#3366FF" },
        { setName: "core", name: "spacing.4", type: "spacing", value: "4" },
        { setName: "core", name: "radius.sm", type: "border-radius", value: "4" },
        { setName: "core", name: "fontSize.14", type: "font-size", value: "14" },
        { setName: "core", name: "lineHeight.tight", type: "number", value: "1.2" },
        { setName: "core", name: "opacity.half", type: "other", value: "0.5" },
    ],
};

describe("tokenVariableName", () => {
    it("splits camelCase words and turns dots into dashes", () => {
        assert.equal(tokenVariableName("fontSize.14"), "--font-size-14");
        assert.equal(tokenVariableName("lineHeight.tight"), "--line-height-tight");
        assert.equal(tokenVariableName("color.semantic.success-bg"), "--color-semantic-success-bg");
        assert.equal(tokenVariableName("radius.sm"), "--radius-sm");
        assert.equal(tokenVariableName("spacing.4"), "--spacing-4");
    });
});

describe("renderTokensCss", () => {
    it("writes one custom property per token, in model order, with one value per type", () => {
        assert.equal(
            renderTokensCss(TOKENS),
            [
                "/* Generated by design-parity generate. Do not edit by hand. */",
                ":root {",
                "    --color-primary-500: #3366FF;",
                "    --spacing-4: 4px;",
                "    --radius-sm: 4px;",
                "    --font-size-14: 14px;",
                "    --line-height-tight: 1.2;",
                "    --opacity-half: 0.5;",
                "}",
                "",
            ].join("\n")
        );
    });
});

describe("colourTokenVariable", () => {
    it("returns the variable of an opaque colour that has a token", () => {
        assert.equal(colourTokenVariable({ hex: "#3366FF", alpha: 1 }, TOKENS), "var(--color-primary-500)");
    });

    it("returns undefined for a translucent colour or a colour without a token", () => {
        assert.equal(colourTokenVariable({ hex: "#3366FF", alpha: 0.5 }, TOKENS), undefined);
        assert.equal(colourTokenVariable({ hex: "#000000", alpha: 1 }, TOKENS), undefined);
    });
});
