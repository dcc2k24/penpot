import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import type { DesignModel, NodeModel } from "../DesignModel.js";
import { FONT_FILES } from "../FontMap.js";
import { PENPOT_FONT_DIR } from "../Paths.js";
import { type ComponentTarget, componentTargets, type ScreenTarget, screenTargets } from "../Targets.js";
import { NodeEmitter, type ResolvedInstance } from "./NodeEmitter.js";
import { renderTokensCss } from "./TokenCss.js";
import { renderTypographyCss } from "./TypographyCss.js";

/** Summary of one generation run. */
export interface GenerateSummary {
    /** Number of component modules written. */
    readonly components: number;
    /** Number of screen modules written. */
    readonly screens: number;
    /** Paths of the files written, relative to the app folder with forward slashes, sorted by code units. */
    readonly files: string[];
    /** Warnings, in generation order. */
    readonly warnings: string[];
}

/** Maps a copy node to the generated component it instantiates, or undefined when the model does not know it. */
type Resolver = (node: NodeModel) => ResolvedInstance | undefined;

/** One import line of a generated module, sorted by its module specifier. */
interface ImportLine {
    /** Module specifier, used for sorting. */
    readonly from: string;
    /** Full import statement. */
    readonly line: string;
}

/** First line of every generated TSX file. */
const TSX_HEADER = "// Generated by design-parity generate. Do not edit by hand.";

/** Source of the generated runtime module, which holds the props types and the helper that nested instances use. */
const RUNTIME_SOURCE = [
    TSX_HEADER,
    "",
    "/** Fill of one element of a component instance: the CSS colour that the element paints with. */",
    "export interface FillStyle {",
    "    /** CSS colour, a background for a shape or a text colour for a text. */",
    "    readonly paint: string;",
    "}",
    "",
    "/** Props of a generated component: overrides by index path inside the component, and placement. */",
    "export interface InstanceProps {",
    "    /** Node id of each element, by index path. The empty path is the root. */",
    "    readonly ids?: Readonly<Record<string, string>>;",
    "    /** Characters of each text element, by index path. */",
    "    readonly texts?: Readonly<Record<string, string>>;",
    "    /** Paint of each element, by index path. */",
    "    readonly fills?: Readonly<Record<string, FillStyle>>;",
    "    /** Width of the root in px. The main board width is used when missing. */",
    "    readonly width?: number;",
    "    /** Height of the root in px. The main board height is used when missing. */",
    "    readonly height?: number;",
    "    /** Left offset of the root in px. Nothing is set when missing. */",
    "    readonly left?: number;",
    "    /** Top offset of the root in px. Nothing is set when missing. */",
    "    readonly top?: number;",
    '    /** CSS position of the root. "relative" is used when missing. */',
    '    readonly position?: "absolute" | "relative";',
    "}",
    "",
    "/** Defaults that a parent gives to a nested instance that it renders. */",
    "export interface InstanceDefaults {",
    "    /** Node id of each element of the copy, by index path. */",
    "    readonly ids: Readonly<Record<string, string>>;",
    "    /** Characters of each text of the copy, by index path. */",
    "    readonly texts: Readonly<Record<string, string>>;",
    "    /** Paint of each element of the copy, by index path. */",
    "    readonly fills: Readonly<Record<string, FillStyle>>;",
    "}",
    "",
    "/**",
    " * Builds the props of a nested instance from the defaults of its copy and the overrides of its parent. The overrides",
    " * of the parent win. Keys under the index are rewritten so that the index becomes the root of the instance.",
    " *",
    " * @param parent - props of the parent component",
    " * @param index - index path of the nested instance inside the parent",
    " * @param defaults - defaults of the copy",
    " */",
    "export function nestedProps(parent: InstanceProps, index: string, defaults: InstanceDefaults): InstanceProps {",
    "    return {",
    "        ids: { ...defaults.ids, ...scopeMap(parent.ids, index) },",
    "        texts: { ...defaults.texts, ...scopeMap(parent.texts, index) },",
    "        fills: { ...defaults.fills, ...scopeMap(parent.fills, index) },",
    "    };",
    "}",
    "",
    "/**",
    " * Keeps the entries under an index path and rewrites their keys relative to that path.",
    " *",
    " * @param map - entries keyed by index path",
    " * @param index - index path to keep",
    " */",
    "function scopeMap<T>(map: Readonly<Record<string, T>> | undefined, index: string): Record<string, T> {",
    "    const scoped: Record<string, T> = {};",
    "    if (map === undefined) {",
    "        return scoped;",
    "    }",
    "    for (const key of Object.keys(map)) {",
    "        if (key === index) {",
    '            scoped[""] = map[key];',
    '        } else if (key.startsWith(index + "/")) {',
    "            scoped[key.slice(index.length + 1)] = map[key];",
    "        }",
    "    }",
    "    return scoped;",
    "}",
    "",
].join("\n");

/**
 * Generates the React app from the design model: one module per component and per screen, the token and typography
 * stylesheets, the route table and the HTML page. Only the generated paths of the app folder are rewritten.
 */
export class ReactGenerator {
    /**
     * Creates a generator.
     *
     * @param model - pulled design model
     * @param appDir - app folder to write into
     * @param fontDir - folder of the Penpot font files that the app copies. Defaults to PENPOT_FONT_DIR.
     */
    public constructor(
        private readonly model: DesignModel,
        private readonly appDir: string,
        private readonly fontDir: string = PENPOT_FONT_DIR
    ) {}

    /**
     * Writes every generated file and returns a summary. The same model always gives the same files.
     *
     * @throws Error when a component cycle, a duplicate name, an unknown font family or a missing font file is found
     */
    public generate(): GenerateSummary {
        const warnings: string[] = [];
        const components = componentTargets(this.model);
        const screens = screenTargets(this.model);
        checkUniqueNames(components, screens);
        const resolve = this.resolver(components);
        checkCycles(components, resolve);
        const outputs = new Map<string, string>();
        for (const target of components) {
            outputs.set(`src/${target.modulePath}`, this.componentModule(target, resolve, warnings));
        }
        for (const screen of screens) {
            outputs.set(`src/${screen.modulePath}`, this.screenModule(screen, resolve, warnings));
        }
        outputs.set("src/tokens.css", renderTokensCss(this.model.tokens));
        outputs.set("src/typography.css", renderTypographyCss(this.model.typographies));
        outputs.set("src/routes.tsx", this.routesModule(components, screens));
        outputs.set("src/runtime.ts", RUNTIME_SOURCE);
        outputs.set("index.html", indexHtml());
        const fontPaths = this.copyFonts();
        this.writeOutputs(outputs);
        const files = [...outputs.keys(), ...fontPaths].sort(compareCodeUnits);
        return { components: components.length, screens: screens.length, files, warnings };
    }

    /**
     * Builds the component module of one library component.
     *
     * @param target - component to render
     * @param resolve - finds the generated component of a copy
     * @param warnings - receives the warnings of the module
     */
    private componentModule(target: ComponentTarget, resolve: Resolver, warnings: string[]): string {
        const file = `src/${target.modulePath}`;
        const emitter = this.emitter(`component ${target.name}`, true, resolve, warnings);
        const body = emitter.renderRoot(target.board);
        const runtime = relativeSpecifier(file, "src/runtime.ts");
        const runtimeLine =
            emitter.nested.size > 0
                ? `import { type InstanceProps, nestedProps } from "${runtime}";`
                : `import type { InstanceProps } from "${runtime}";`;
        const imports: ImportLine[] = [
            { from: runtime, line: runtimeLine },
            ...nestedImports(file, emitter.nested),
            reactImport(),
        ];
        return moduleText(imports, [
            `/** Component ${target.name}. Props override the ids, texts and paints of an instance. */`,
            `export function ${target.componentName}(props: InstanceProps = {}): ReactElement {`,
            "    return (",
            ...body,
            "    );",
            "}",
        ]);
    }

    /**
     * Builds the screen module of one journey board.
     *
     * @param target - screen to render
     * @param resolve - finds the generated component of a copy
     * @param warnings - receives the warnings of the module
     */
    private screenModule(target: ScreenTarget, resolve: Resolver, warnings: string[]): string {
        const file = `src/${target.modulePath}`;
        const emitter = this.emitter(`screen ${target.id}`, false, resolve, warnings);
        const body = emitter.renderRoot(target.board);
        const imports: ImportLine[] = [...nestedImports(file, emitter.nested), reactImport()];
        return moduleText(imports, [
            `/** Screen ${target.name}, the board of the ${target.journey} journey. */`,
            `export function ${target.componentName}(): ReactElement {`,
            "    return (",
            ...body,
            "    );",
            "}",
        ]);
    }

    /**
     * Builds the route table and the index page.
     *
     * @param components - component targets, in target order
     * @param screens - screen targets, in target order
     */
    private routesModule(components: ComponentTarget[], screens: ScreenTarget[]): string {
        const file = "src/routes.tsx";
        const imports: ImportLine[] = [reactImport()];
        for (const screen of screens) {
            const from = relativeSpecifier(file, `src/${screen.modulePath}`);
            imports.push({ from, line: `import { ${screen.componentName} } from "${from}";` });
        }
        for (const component of components) {
            const from = relativeSpecifier(file, `src/${component.modulePath}`);
            imports.push({ from, line: `import { ${component.componentName} } from "${from}";` });
        }
        const entries: string[] = [];
        for (const screen of screens) {
            entries.push(...routeEntry(screen.route, screen.name, screen.componentName));
        }
        for (const component of components) {
            entries.push(...routeEntry(component.route, component.name, component.componentName));
        }
        const links = [
            ...screens.map((screen) => ({ route: screen.route, label: screen.name })),
            ...components.map((component) => ({ route: component.route, label: component.name })),
        ];
        const screenLinks = links.slice(0, screens.length);
        const componentLinks = links.slice(screens.length);
        return moduleText(imports, [
            "export interface AppRoute {",
            "    readonly path: string;",
            "    readonly label: string;",
            "    render(): ReactElement;",
            "}",
            "",
            "export const routes: AppRoute[] = [",
            ...entries,
            "];",
            "",
            "/** Index page that links to every route, under the headings Screens and Components. */",
            "export function IndexPage(): ReactElement {",
            "    return (",
            "        <main>",
            "            <h1>Design Lab parity app</h1>",
            "            <h2>Screens</h2>",
            "            <ul>",
            ...linkLines(screenLinks),
            "            </ul>",
            "            <h2>Components</h2>",
            "            <ul>",
            ...linkLines(componentLinks),
            "            </ul>",
            "        </main>",
            "    );",
            "}",
        ]);
    }

    /**
     * Creates a node emitter for one module.
     *
     * @param where - name of the module, for warnings
     * @param dynamic - true for a component module
     * @param resolve - finds the generated component of a copy
     * @param warnings - receives the warnings
     */
    private emitter(where: string, dynamic: boolean, resolve: Resolver, warnings: string[]): NodeEmitter {
        return new NodeEmitter({
            tokens: this.model.tokens,
            typographies: this.model.typographies,
            dynamic,
            where,
            warn: (message) => warnings.push(message),
            resolve,
        });
    }

    /**
     * Builds the function that finds the generated component of a copy, from the component ids of the model.
     *
     * @param components - component targets, in target order
     */
    private resolver(components: ComponentTarget[]): Resolver {
        const byComponentId = new Map<string, ResolvedInstance>();
        for (const component of this.model.components) {
            const target = components.find((candidate) => candidate.mainBoardId === component.mainInstanceId);
            if (target !== undefined) {
                byComponentId.set(component.id, {
                    componentName: target.componentName,
                    modulePath: target.modulePath,
                    main: target.board,
                });
            }
        }
        return (node) => (node.component === null ? undefined : byComponentId.get(node.component.componentId));
    }

    /**
     * Copies every font file of the font table into the public folder of the app, so that Vite serves it at /fonts/.
     * The source files are all checked before the folder is rewritten.
     *
     * @returns paths of the copies, relative to the app folder with forward slashes
     * @throws Error when a source font file is missing
     */
    private copyFonts(): string[] {
        for (const font of FONT_FILES) {
            const source = join(this.fontDir, font.file);
            if (!existsSync(source)) {
                throw new Error(
                    `font file missing: ${source}. Set PENPOT_FONT_DIR to the folder of the Penpot font files.`
                );
            }
        }
        const target = join(this.appDir, "public", "fonts");
        rmSync(target, { recursive: true, force: true });
        mkdirSync(target, { recursive: true });
        const paths: string[] = [];
        for (const font of FONT_FILES) {
            copyFileSync(join(this.fontDir, font.file), join(target, font.file));
            paths.push(`public/fonts/${font.file}`);
        }
        return paths;
    }

    /**
     * Deletes the generated paths and writes the new files.
     *
     * @param outputs - file contents by path relative to the app folder
     */
    private writeOutputs(outputs: Map<string, string>): void {
        const src = join(this.appDir, "src");
        rmSync(join(src, "components"), { recursive: true, force: true });
        rmSync(join(src, "screens"), { recursive: true, force: true });
        for (const file of ["src/tokens.css", "src/typography.css", "src/routes.tsx", "src/runtime.ts", "index.html"]) {
            rmSync(join(this.appDir, ...file.split("/")), { force: true });
        }
        for (const [file, content] of outputs) {
            const path = join(this.appDir, ...file.split("/"));
            mkdirSync(dirname(path), { recursive: true });
            writeFileSync(path, content, "utf8");
        }
    }
}

/**
 * Checks that every generated component and screen has its own name.
 *
 * @param components - component targets
 * @param screens - screen targets
 * @throws Error when two modules get the same React name
 */
function checkUniqueNames(components: ComponentTarget[], screens: ScreenTarget[]): void {
    const owners = new Map<string, string>();
    const claim = (name: string, owner: string): void => {
        const previous = owners.get(name);
        if (previous !== undefined) {
            throw new Error(`duplicate React name ${name}: ${previous} and ${owner}`);
        }
        owners.set(name, owner);
    };
    for (const target of components) {
        claim(target.componentName, `component ${target.name}`);
    }
    for (const screen of screens) {
        claim(screen.componentName, `screen ${screen.name}`);
    }
}

/**
 * Checks that no component renders itself, directly or through other components.
 *
 * @param components - component targets
 * @param resolve - finds the generated component of a copy
 * @throws Error with the cycle when there is one
 */
function checkCycles(components: ComponentTarget[], resolve: Resolver): void {
    const done = new Set<string>();
    const visit = (name: string, board: NodeModel, stack: string[]): void => {
        if (done.has(name)) {
            return;
        }
        if (stack.includes(name)) {
            throw new Error(`component cycle: ${[...stack, name].join(" -> ")}`);
        }
        for (const copy of topLevelCopies(board)) {
            const resolved = resolve(copy);
            if (resolved !== undefined) {
                visit(resolved.componentName, resolved.main, [...stack, name]);
            }
        }
        done.add(name);
    };
    for (const target of components) {
        visit(target.componentName, target.board, []);
    }
}

/**
 * Lists the copies that a module renders directly. A copy is a leaf: its children belong to the component it copies.
 *
 * @param node - node to search
 */
function topLevelCopies(node: NodeModel): NodeModel[] {
    if (node.component !== null && node.component.mainInstance === false) {
        return [node];
    }
    return node.children.flatMap((child) => topLevelCopies(child));
}

/**
 * Lists the import lines of the nested components of a module.
 *
 * @param file - path of the module, relative to the app folder
 * @param nested - nested components, by component name
 */
function nestedImports(file: string, nested: Map<string, ResolvedInstance>): ImportLine[] {
    const imports: ImportLine[] = [];
    for (const resolved of nested.values()) {
        const from = relativeSpecifier(file, `src/${resolved.modulePath}`);
        imports.push({ from, line: `import { ${resolved.componentName} } from "${from}";` });
    }
    return imports;
}

/**
 * Returns the import line of the ReactElement type.
 */
function reactImport(): ImportLine {
    return { from: "react", line: 'import type { ReactElement } from "react";' };
}

/**
 * Returns the import specifier of a module from another module, with the .js suffix.
 *
 * @param fromFile - path of the importing module, relative to the app folder
 * @param toFile - path of the imported module, relative to the app folder
 */
function relativeSpecifier(fromFile: string, toFile: string): string {
    const target = toFile.replace(/\.tsx?$/, ".js");
    const relative = posix.relative(posix.dirname(fromFile), target);
    return relative.startsWith(".") ? relative : `./${relative}`;
}

/**
 * Joins the header, the sorted imports and the body of a module.
 *
 * @param imports - import lines, in any order
 * @param body - body lines of the module
 */
function moduleText(imports: ImportLine[], body: string[]): string {
    const sorted = [...imports].sort((a, b) => compareCodeUnits(a.from, b.from)).map((item) => item.line);
    return [TSX_HEADER, ...sorted, "", ...body, ""].join("\n");
}

/**
 * Returns the route entry lines of one route.
 *
 * @param route - route path
 * @param label - label of the route
 * @param componentName - React name of the component to render
 */
function routeEntry(route: string, label: string, componentName: string): string[] {
    return [
        "    {",
        `        path: ${JSON.stringify(route)},`,
        `        label: ${JSON.stringify(label)},`,
        `        render: () => <${componentName} />,`,
        "    },",
    ];
}

/**
 * Returns the list item lines of the index page.
 *
 * @param links - routes and their labels
 */
function linkLines(links: { route: string; label: string }[]): string[] {
    const lines: string[] = [];
    for (const link of links) {
        lines.push(
            "                <li>",
            `                    <a href={${JSON.stringify(link.route)}}>{${JSON.stringify(link.label)}}</a>`,
            "                </li>"
        );
    }
    return lines;
}

/**
 * Returns the Vite entry page of the app.
 */
function indexHtml(): string {
    return [
        "<!doctype html>",
        '<html lang="en">',
        "  <head>",
        '    <meta charset="UTF-8" />',
        '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
        "    <title>Design Lab parity app</title>",
        '    <link rel="stylesheet" href="/src/tokens.css" />',
        '    <link rel="stylesheet" href="/src/typography.css" />',
        "  </head>",
        "  <body>",
        '    <div id="root"></div>',
        '    <script type="module" src="/src/main.tsx"></script>',
        "  </body>",
        "</html>",
        "",
    ].join("\n");
}

/**
 * Compares two strings by their UTF-16 code units, so that the order does not depend on the locale.
 *
 * @param a - first string
 * @param b - second string
 */
function compareCodeUnits(a: string, b: string): number {
    if (a === b) {
        return 0;
    }
    return a < b ? -1 : 1;
}
