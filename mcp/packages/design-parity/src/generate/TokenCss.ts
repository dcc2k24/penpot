import type { Colour } from "../Colour.js";
import { normaliseHex } from "../Colour.js";
import type { TokenModel, TokensModel } from "../DesignModel.js";

/** Comment that starts every CSS file the generator writes. */
export const GENERATED_CSS_HEADER = "/* Generated by design-parity generate. Do not edit by hand. */";

/**
 * Turns a token name into a CSS custom property name. Dots become dashes, each camelCase word is split with a dash and
 * the result is lower case, so "fontSize.14" becomes "--font-size-14".
 *
 * @param name - token name, for example "lineHeight.tight"
 */
export function tokenVariableName(name: string): string {
    const words = name
        .replace(/\./g, "-")
        .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
        .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
        .toLowerCase()
        .replace(/[^a-z0-9-]+/g, "-");
    return `--${words}`;
}

/**
 * Renders the tokens of a model as one `:root` block of custom properties, in model order.
 *
 * @param tokens - token sets, themes and tokens of the design
 */
export function renderTokensCss(tokens: TokensModel): string {
    const lines = [GENERATED_CSS_HEADER, ":root {"];
    for (const token of tokens.tokens) {
        lines.push(`    ${tokenVariableName(token.name)}: ${tokenValueCss(token)};`);
    }
    lines.push("}", "");
    return lines.join("\n");
}

/**
 * Finds the colour token of a colour, as a `var()` reference. Only an opaque colour can use a token.
 *
 * @param colour - colour to look up, with its alpha
 * @param tokens - token sets, themes and tokens of the design
 * @returns `var(--...)` for the first colour token with the same hex, or undefined when there is none
 */
export function colourTokenVariable(colour: Colour, tokens: TokensModel): string | undefined {
    if (colour.alpha !== 1) {
        return undefined;
    }
    const token = tokens.tokens.find(
        (candidate) => candidate.type === "color" && opaqueHexOf(candidate) === colour.hex
    );
    return token === undefined ? undefined : `var(${tokenVariableName(token.name)})`;
}

/**
 * Returns the CSS value of one token: a colour as stored, a length in px, or the value text.
 *
 * @param token - token to format
 * @throws Error when a length token has no number value
 */
function tokenValueCss(token: TokenModel): string {
    switch (token.type) {
        case "spacing":
        case "border-radius":
        case "font-size":
            return pixelsOf(token);
        default:
            return token.value;
    }
}

/**
 * Formats the number of a length token as px.
 *
 * @param token - token whose value is a number
 * @throws Error when the value is not a number
 */
function pixelsOf(token: TokenModel): string {
    const amount = Number(token.value);
    if (token.value.trim() === "" || !Number.isFinite(amount)) {
        throw new Error(`token ${token.name} has no number value: ${token.value}`);
    }
    return `${amount}px`;
}

/**
 * Returns the upper case hex of a token value when the value is an opaque hex colour, or undefined otherwise.
 *
 * @param token - colour token
 */
function opaqueHexOf(token: TokenModel): string | undefined {
    try {
        const colour = normaliseHex(token.value);
        return colour.alpha === 1 ? colour.hex : undefined;
    } catch {
        return undefined;
    }
}
