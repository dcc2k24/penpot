import assert from "node:assert/strict";
import { describe, it } from "node:test";
import type { TypographyModel } from "../DesignModel.js";
import { renderTypographyCss } from "./TypographyCss.js";

const TYPOGRAPHIES: TypographyModel[] = [
    {
        id: "t1",
        name: "body-sm",
        fontFamily: "Source Sans Pro",
        fontSize: 14,
        fontWeight: "400",
        lineHeight: 1.4,
        letterSpacing: null,
        textTransform: null,
    },
    {
        id: "t2",
        name: "Heading XL",
        fontFamily: "Source Sans Pro",
        fontSize: 32,
        fontWeight: "700",
        lineHeight: null,
        letterSpacing: 0.5,
        textTransform: "uppercase",
    },
];

describe("renderTypographyCss", () => {
    it("writes one @font-face rule per font file, then one class per text style", () => {
        assert.equal(
            renderTypographyCss(TYPOGRAPHIES),
            [
                "/* Generated by design-parity generate. Do not edit by hand. */",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: normal;",
                "    font-weight: 400;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-regular.woff\") format('woff');",
                "}",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: italic;",
                "    font-weight: 400;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-italic.woff\") format('woff');",
                "}",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: normal;",
                "    font-weight: 600;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-semibold.woff\") format('woff');",
                "}",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: italic;",
                "    font-weight: 600;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-semibolditalic.woff\") format('woff');",
                "}",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: normal;",
                "    font-weight: 700;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-bold.woff\") format('woff');",
                "}",
                "@font-face {",
                "    font-family: 'sourcesanspro';",
                "    font-style: italic;",
                "    font-weight: 700;",
                "    font-display: block;",
                "    src: url(\"/fonts/sourcesanspro-bolditalic.woff\") format('woff');",
                "}",
                ".typo-body-sm {",
                '    font-family: "sourcesanspro";',
                "    font-size: 14px;",
                "    font-weight: 400;",
                "    line-height: 1.4;",
                "}",
                ".typo-heading-xl {",
                '    font-family: "sourcesanspro";',
                "    font-size: 32px;",
                "    font-weight: 700;",
                "    letter-spacing: 0.5px;",
                "    text-transform: uppercase;",
                "}",
                "",
            ].join("\n")
        );
    });
});
